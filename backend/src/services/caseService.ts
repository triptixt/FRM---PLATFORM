import { query } from '../config/database';
import { RiskAssessment, FraudCase } from '../core/types';
import { logger } from '../utils/logger';

export class CaseService {
  private static sequence = 1;

  public static async createCase(assessment: RiskAssessment, merchantId: string): Promise<string | null> {
    try {
      // Check if case already exists for this txnId
      const existing = await query(`SELECT case_id FROM frm_case WHERE txn_id = $1 LIMIT 1`, [assessment.txnId]);
      if (existing.rows.length > 0) {
        logger.debug(`Case already exists for txn=${assessment.txnId}`);
        return null;
      }

      const caseRef = await this.generateCaseRef();

      const insertRes = await query(
        `INSERT INTO frm_case
         (case_ref, txn_id, merchant_id, risk_score, decision, triggered_rules, case_status)
         VALUES ($1, $2, $3, $4, $5, $6, 'OPEN')
         RETURNING case_id`,
        [
          caseRef,
          assessment.txnId,
          merchantId,
          assessment.riskScore,
          assessment.decision,
          JSON.stringify(assessment.triggeredRules),
        ]
      );

      const caseId = insertRes.rows[0].case_id;

      // Audit trail
      await this.writeAudit(
        caseId,
        caseRef,
        'system',
        null,
        'OPEN',
        null,
        'Case auto-generated by rule engine'
      );

      logger.info(
        `Case created: ref=${caseRef} txn=${assessment.txnId} score=${assessment.riskScore} decision=${assessment.decision}`
      );

      return caseRef;
    } catch (err: any) {
      logger.error(`Error creating fraud case for txn ${assessment.txnId}: ${err.message}`);
      return null;
    }
  }

  public static async updateCaseStatus(
    caseId: number | string,
    newStatus: string,
    remarks?: string | null,
    assignedTo?: string | null,
    changedBy: string = 'system'
  ): Promise<FraudCase> {
    const existingRes = await query(`SELECT * FROM frm_case WHERE case_id = $1`, [caseId]);
    if (existingRes.rows.length === 0) {
      throw new Error(`Case not found: ${caseId}`);
    }

    const currentCase = existingRes.rows[0];
    const oldStatus = currentCase.case_status;

    const updateRes = await query(
      `UPDATE frm_case
       SET case_status = $1,
           remarks = COALESCE($2, remarks),
           assigned_to = COALESCE($3, assigned_to),
           updated_at = NOW()
       WHERE case_id = $4
       RETURNING *`,
      [newStatus, remarks || null, assignedTo || null, caseId]
    );

    const updated = updateRes.rows[0];

    // Write audit trail
    await this.writeAudit(
      caseId,
      updated.case_ref,
      changedBy,
      oldStatus,
      newStatus,
      assignedTo || currentCase.assigned_to,
      remarks || null
    );

    logger.info(`Case ${updated.case_ref} updated: ${oldStatus} → ${newStatus} by ${changedBy}`);

    return {
      caseId: parseInt(updated.case_id, 10),
      caseRef: updated.case_ref,
      txnId: updated.txn_id,
      merchantId: updated.merchant_id,
      riskScore: updated.risk_score,
      decision: updated.decision,
      triggeredRules: typeof updated.triggered_rules === 'string' ? JSON.parse(updated.triggered_rules) : updated.triggered_rules,
      caseStatus: updated.case_status,
      assignedTo: updated.assigned_to,
      remarks: updated.remarks,
      createdAt: updated.created_at,
      updatedAt: updated.updated_at,
    };
  }

  public static async writeAudit(
    caseId: number | string,
    caseRef: string,
    changedBy: string,
    oldStatus: string | null,
    newStatus: string,
    assignedTo?: string | null,
    remarks?: string | null
  ): Promise<void> {
    try {
      await query(
        `INSERT INTO frm_case_audit
         (case_id, case_ref, changed_by, old_status, new_status, assigned_to, remarks)
         VALUES ($1, $2, $3, $4, $5, $6, $7)`,
        [caseId, caseRef, changedBy, oldStatus, newStatus, assignedTo || null, remarks || null]
      );
    } catch (err: any) {
      logger.warn(`Failed to write case audit for ${caseRef}: ${err.message}`);
    }
  }

  private static async generateCaseRef(): Promise<string> {
    const year = new Date().getFullYear();
    try {
      const countRes = await query(`SELECT COUNT(*) FROM frm_case`);
      const total = parseInt(countRes.rows[0].count, 10) + 1;
      return `CASE-${year}-${String(total).padStart(6, '0')}`;
    } catch {
      return `CASE-${year}-${String(this.sequence++).padStart(6, '0')}`;
    }
  }
}

